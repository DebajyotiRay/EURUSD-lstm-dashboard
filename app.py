"""
app.py
------
Flask backend for the EURUSD LSTM Dashboard (Plotly edition).

Design note (changed from the original version): predictions are now
generated by a background scheduler (APScheduler) on a fixed interval,
independent of page views. The original version re-ran the full
subprocess -> fetch data -> reload model -> run inference pipeline on
EVERY page load and every 30-second auto-refresh, which is wasteful and
would hammer external data sources under any real traffic. Now the page
just reads the latest cached prediction_results.json.

Routes:
  GET  /          -> renders the dashboard page with embedded Plotly charts
  GET  /health    -> simple health check for deployment platforms
  POST /refresh   -> triggers an immediate prediction run, then redirects to /
"""

import json
