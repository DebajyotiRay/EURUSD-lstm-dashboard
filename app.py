import os
import sys
from datetime import datetime

from apscheduler.schedulers.background import BackgroundScheduler
from flask import Flask, jsonify, redirect, render_template_string, url_for

import lstm_core as core

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    stream=sys.stdout,
)
logger = logging.getLogger("app")

app = Flask(__name__)
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE_DIR, "lstm_model.pth")
RESULTS_PATH = os.path.join(BASE_DIR, "prediction_results.json")

# Refresh interval in seconds. Configurable via env var for deployment.
REFRESH_INTERVAL_SECONDS = int(os.environ.get("REFRESH_INTERVAL_SECONDS", "60"))

_model = None  # loaded lazily, once, on first use


def get_model():
    global _model
    if _model is None:
        _model = core.load_model(MODEL_PATH)
    return _model


def run_prediction_job():
    """Fetch data, run the model, and write prediction_results.json.
    Any failure is logged and swallowed so the scheduler keeps running."""
    try:
        model = get_model()
        raw_data, data_source = core.get_market_data()
        raw_data = raw_data.iloc[-core.REQUIRED_BARS:]
        feature_frame = core.build_feature_frame(raw_data)
        run = core.run_backtest_and_forecast(model, feature_frame)

        metrics = core.regression_metrics(run.true_prices, run.predicted_prices)
        dir_acc = core.directional_accuracy(run.true_prices, run.predicted_prices)

        results = {
            "predicted_prices": run.predicted_prices,
            "true_prices": run.true_prices,
            "timestamps": run.timestamps,
            "percent_change": run.percent_change,
            "next_prediction": run.next_prediction,
            "data_source": data_source,
            "mae": metrics["mae"],
            "rmse": metrics["rmse"],
            "directional_accuracy": dir_acc,
            "generated_at": datetime.now().isoformat(timespec="seconds"),
        }
        with open(RESULTS_PATH, "w") as f:
            json.dump(results, f)
        logger.info("Prediction refreshed. Source: %s", data_source)
    except Exception:
        logger.exception("Prediction job failed; keeping last known results.")


def load_results():
    if not os.path.exists(RESULTS_PATH):
        return None, "No predictions generated yet. Click Refresh Now or wait for the first scheduled run."
    try:
        with open(RESULTS_PATH) as f:
            return json.load(f), None
    except Exception as exc:
        return None, f"Failed to parse prediction_results.json: {exc}"


def build_charts(results):
    """Build Plotly chart HTML strings from prediction results."""
    import plotly.graph_objects as go

    timestamps = results["timestamps"]
    true_prices = results["true_prices"]
    pred_prices = results["predicted_prices"]
    EPS = 1e-10

    fig_price = go.Figure()
    fig_price.add_trace(go.Scatter(
        x=timestamps, y=true_prices, mode="lines+markers", name="Actual (normalised)",
        line=dict(color="#2e7d32", width=2), marker=dict(size=4),
    ))
    fig_price.add_trace(go.Scatter(
        x=timestamps, y=pred_prices, mode="lines+markers", name="Predicted (normalised)",
        line=dict(color="#1565c0", width=2, dash="dash"), marker=dict(size=4),
    ))
    fig_price.update_layout(
        title="True vs Predicted Close Price (normalised 0-1)",
        xaxis_title="Time (UTC)", yaxis_title="Normalised price",
        hovermode="x unified", legend=dict(orientation="h", y=1.08),
        margin=dict(l=50, r=20, t=60, b=50),
        plot_bgcolor="#fafafa", paper_bgcolor="#ffffff",
    )
    fig_price.update_xaxes(showgrid=True, gridcolor="#eeeeee")
    fig_price.update_yaxes(showgrid=True, gridcolor="#eeeeee")

    pct_true = [
        ((true_prices[i] - true_prices[i - 1]) / (abs(true_prices[i - 1]) + EPS)) * 100
        for i in range(1, len(true_prices))
    ]
    pct_pred = [
        ((pred_prices[i] - pred_prices[i - 1]) / (abs(pred_prices[i - 1]) + EPS)) * 100
        for i in range(1, len(pred_prices))
    ]

    fig_pct = go.Figure()
    fig_pct.add_trace(go.Bar(x=timestamps[1:], y=pct_true, name="Actual % change", marker_color="#2e7d32", opacity=0.75))
    fig_pct.add_trace(go.Bar(x=timestamps[1:], y=pct_pred, name="Predicted % change", marker_color="#1565c0", opacity=0.75))
    fig_pct.update_layout(
        title="Bar-by-Bar % Change: Actual vs Predicted",
        xaxis_title="Time (UTC)", yaxis_title="% change", barmode="group",
        hovermode="x unified", legend=dict(orientation="h", y=1.08),
        margin=dict(l=50, r=20, t=60, b=50),
        plot_bgcolor="#fafafa", paper_bgcolor="#ffffff",
    )
    fig_pct.update_xaxes(showgrid=True, gridcolor="#eeeeee")
    fig_pct.update_yaxes(showgrid=True, gridcolor="#eeeeee", zeroline=True, zerolinecolor="#aaa")

    price_html = fig_price.to_html(full_html=False, include_plotlyjs="cdn", div_id="priceChart")
    pct_html = fig_pct.to_html(full_html=False, include_plotlyjs=False, div_id="pctChart")
    return price_html, pct_html


